#compute basline MF sumrate for both validation and testing dataset
def precompute_mf_rates(H_complex_tensor): #here H_complex_tensor is the entire validation or testing dataset depending on arguments passed in 157,158 line
    H_np_all = H_complex_tensor.numpy()

    return np.array([matched_filter_zf_baseline_rate(H_np_all[i]) for i in range(H_np_all.shape[0])])

val_mf_rates_cached  = precompute_mf_rates(val_dataset.H_complex)
test_mf_rates_cached = precompute_mf_rates(test_dataset.H_complex)

# Helper: run a full pass over a loader (used for validation and test)
def evaluate(loader, model, mf_rates_cached): # testing or validation, depends on the loader passed

    model.eval() # model runs in evaluation mode, ComplexBN uses the running statistics now
    val_net_rates= []  #These will store one sum-rate per channel realization.
    with torch.no_grad(): #gradients are not computed , because evaluation only needs forward flow 
        for H_tensor, H_complex in loader: 
            #loader feeds H_tensor and H_Complex batch wise with shuffling, i.e for every iteration H_tensor = BxMxK
            H_tensor = H_tensor.to(device)
            F_RF = model(H_tensor) # Size: B x M x Nrf
            F_BB, _, _ = kkt_digital_precoder_torch(H_tensor, F_RF, noise_power, P_t)  # Size: B x Nrf X K
            H_np_batch = H_complex.numpy() 
            val_net_rates.append(sum_rate_torch( H=H_tensor, F_RF=F_RF, F_BB= F_BB, noise_power= noise_power, P_t=P_t).item())

                
    return float(np.mean(val_net_rates)), float(np.mean(mf_rates_cached))

train_loss_history = []
train_rate_history = []
val_rate_history = []
def save_checkpoint(path, epoch, best_val_rate, best_epoch, epochs_no_improve):
    torch.save({
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict(),
        'scheduler_state_dict': scheduler.state_dict(),
        'epoch': epoch,
        'best_val_rate': best_val_rate,
        'best_epoch': best_epoch,
        'epochs_no_improve': epochs_no_improve,
    }, path)

# TRAINING LOOP (with validation, early stopping, checkpointing)
# ══════════════════════════════════════════════════════════════════════════
#check if already trained model exist upto some epochs
if RESUME and os.path.exists(LATEST_MODEL_PATH):
    checkpoint = torch.load(LATEST_MODEL_PATH, weights_only=False)

    model.load_state_dict(checkpoint["model_state_dict"])
    optimizer.load_state_dict(checkpoint["optimizer_state_dict"])
    scheduler.load_state_dict(checkpoint["scheduler_state_dict"])

    start_epoch = checkpoint["epoch"] + 1
    best_val_rate = checkpoint["best_val_rate"]

    best_epoch = checkpoint.get("best_epoch", checkpoint["epoch"])
    epochs_no_improve = checkpoint.get("epochs_no_improve", 0)

    print(f"Resuming training from epoch {start_epoch}")
else : 
    start_epoch= 1   
    best_val_rate = -np.inf
    best_epoch = 0
    epochs_no_improve = 0 #How many consecutive epochs have NOT improved the validation rate?

print(f"\n{'Epoch':>6}  {'Train Loss':>11}  {'Train R':>9}  {'Val R':>9}  "
      f"{'MF R':>9}  {'%MF':>7}  {'LR':>9}  {'ES cnt':>7}  {'Best R':>9}")
print("-" * 95)

for epoch in range(start_epoch, MAX_EPOCHS + 1):
    # ── Train phase ──────────────────────────────────────────────────────
    model.train()
    epoch_losses = [] 
    train_net_rates = [] #They will collect one value per batch

    for H_tensor, H_complex in train_loader: # The loop processes one batch at a time.
        H_tensor = H_tensor.to(device)

        # Forward: predict analog precoder F_RF
        F_RF = model(H_tensor) # (batch,M,K) --> (1024,M,Nrf)

        # Loss (surrogate, differentiable), consuming the exact same H_tensor representation the model just consumed.
        
        loss = concentrated_mse_loss(H_tensor, F_RF, noise_power, P_t) # average concentrated MSE over all 1024 channel realizations in the batch.

        # clear previous gradients
        optimizer.zero_grad()
        #Bckpropogate using the loss
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0) #scales all gradients if the overall their overall norm exceeds 5.
        #update parameters
        optimizer.step()
        # Adam performs W_new= W_old − η⋅Update
        epoch_losses.append(loss.item())

        # Track actual training sum-rate (non-differentiable, for logging
        # only), using the KKT digital precoder -- fed the same H_tensor --
        # plus the numpy-based sum_rate() metric.
        with torch.no_grad():
            F_BB, _, _ = kkt_digital_precoder_torch(H_tensor, F_RF, noise_power, P_t)
            F_RF_dt = F_RF;
            train_net_rates.append(sum_rate_torch( H=H_tensor, F_RF=F_RF, F_BB= F_BB, noise_power= noise_power, P_t=P_t).item())
    avg_train_loss = float(np.mean(epoch_losses))  # Training loss (concentrated mse) per epoch
    avg_train_rate = float(np.mean(train_net_rates)) #avg sum rate per epoch

    # Now The first half of the epoch that is update the network weights is done.

    # ── Validation phase 

    avg_val_rate, avg_mf_rate = evaluate(val_loader, model, val_mf_rates_cached)
    pct_of_mf = 100.0 * avg_val_rate / avg_mf_rate if avg_mf_rate != 0 else float('nan')
    train_loss_history.append(avg_train_loss)
    train_rate_history.append(avg_train_rate)
    val_rate_history.append(avg_val_rate)
    # Step the LR scheduler on validation sum-rate (maximize).
    scheduler.step(avg_val_rate) #This scheduler monitors Validation Sum Rate
    current_lr = optimizer.param_groups[0]['lr']

    # ── Early stopping / checkpointing 
    if avg_val_rate > best_val_rate + ES_MIN_DELTA:
        best_val_rate = avg_val_rate
        best_epoch = epoch
        epochs_no_improve = 0
        save_checkpoint(MODEL_2_PATH, epoch, best_val_rate, best_epoch,epochs_no_improve) # epoch is current and best epoch 
    else:
        epochs_no_improve += 1
    save_checkpoint(
    LATEST_MODEL_PATH,
    epoch,
    best_val_rate,
    best_epoch,
    epochs_no_improve,
    )

    print(f"{epoch:>6}  {avg_train_loss:>11.4f}  {avg_train_rate:>7.3f} b/s  "
          f"{avg_val_rate:>7.3f} b/s  {avg_mf_rate:>7.3f} b/s  {pct_of_mf:>6.1f}%  "
          f"{current_lr:>9.2e}  {epochs_no_improve:>7}  {best_val_rate:>7.3f} b/s")

    if epochs_no_improve >= ES_PATIENCE:
        print(f"\nEarly stopping triggered at epoch {epoch} "
              f"(no improvement for {ES_PATIENCE} epochs). "
              f"Best val sum-rate: {best_val_rate:.3f} b/s at epoch {best_epoch}.")
        break


print(f"\nTraining finished. Best validation sum-rate: {best_val_rate:.3f} b/s "
      f"at epoch {best_epoch}. Checkpoint: {MODEL_2_PATH}")

