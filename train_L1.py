# 1. DATASET GENERATION
# generate entire dataset used in one epoch, later divide and convert to tensor
def generate_channel_dataset(n_samples, rng):
    """Generate n_samples independent multiuser near-field channel
    realizations of shape (n_samples, M, K), complex128."""
    channels = np.stack([
        generate_channel_los(K=K, M=M, d=d, wavelength=WL,
                          r_min=r_min, r_max=r_max, rng=rng)[0]
        for _ in range(n_samples)
    ]) 
    return channels # Returns numpy.ndarray - (n_samples, M, K) complex 


print(f"\nGenerating {N_SAMPLES} channel realizations (M={M}, K={K})...")
data_rng = np.random.default_rng(SEED)
H_all = generate_channel_dataset(N_SAMPLES, data_rng)  # (N_SAMPLES, M, K) complex


# 2. TRAIN / VALIDATION / TEST SPLIT (70 / 15 / 15)
n_train = int(N_SAMPLES * TRAIN_FRAC)   # 14000
n_val   = int(N_SAMPLES * VAL_FRAC)     # 3000
n_test  = N_SAMPLES - n_train - n_val   # 3000

# Shuffle once, deterministically, before slicing.
perm = data_rng.permutation(N_SAMPLES)
H_all = H_all[perm]

H_train = H_all[:n_train]
H_val   = H_all[n_train:n_train + n_val]
H_test  = H_all[n_train + n_val:]


#Pytorch Dataset
class MultiuserChannelDataset(Dataset):
    def __init__(self, H_np):
        self.H_tensor = torch.as_tensor (H_np, dtype=torch.cfloat)  # stays on device
        self.H_complex = torch.as_tensor (H_np, dtype=torch.cfloat )  # stays on CPU
        
    def __len__(self):
        return self.H_complex.shape[0]

    def __getitem__(self, idx):
        return self.H_tensor[idx], self.H_complex[idx]

#Dataset : Each Data set has H_tensor, H_complex
train_dataset = MultiuserChannelDataset(H_train)
val_dataset   = MultiuserChannelDataset(H_val)
test_dataset  = MultiuserChannelDataset(H_test)

# Data loader for each data set : The DataLoader the data set into batches, each batch having H_tensor and H_complex of size B x M xK
train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True,  drop_last=False)
val_loader   = DataLoader(val_dataset,   batch_size=BATCH_SIZE, shuffle=False, drop_last=False)
test_loader  = DataLoader(test_dataset,  batch_size=BATCH_SIZE, shuffle=False, drop_last=False)


# Matched-filter (phase-conjugate) + ZF-digital baseline
def matched_filter_zf_baseline_rate(H_np):
    F_RF_mf = np.exp(1j * np.angle(H_np[:, :N_RF])) / np.sqrt(M)
    H_eq = H_np.conj().T @ F_RF_mf          # (K, N_RF)
    F_BB_zf = np.linalg.pinv(H_eq)          # (N_RF, K)
    pwr = np.linalg.norm(F_RF_mf @ F_BB_zf, 'fro') ** 2
    F_BB_zf *= np.sqrt(P_t / pwr)
    return sum_rate(H_np, F_RF_mf, F_BB_zf, noise_power)

# Model / optimizer / scheduler
#object of the neural network
model = MultiuserAnalogPrecoderNet(M=M, K=K,T=0, N_RF=N_RF, mlp_dims=MLP_DIMS).to(device)
# the optimizer uses the gradients to adjust the parameters.
optimizer = optim.AdamW(model.parameters(), lr=LR, weight_decay=1e-4) # model.parameters() returns Every trainable parameter inside your network is collected automatically.
# mode='max' because we're tracking validation sum-rate, which should be  maximized (unlike a loss, which is minimized).
#updates the learning rate
scheduler = optim.lr_scheduler.ReduceLROnPlateau(
    optimizer, mode='max', factor=SCHED_FACTOR,
    patience=SCHED_PATIENCE, threshold=SCHED_THRESH
)

n_params = sum(p.numel() for p in model.parameters()) #counts no. of parameters

